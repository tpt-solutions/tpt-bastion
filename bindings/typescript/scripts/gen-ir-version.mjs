// Generate src/ir-version.ts from the Rust source of truth, so the binding's
// IR version cannot drift from the compiler's. Run before every build.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const rust = join(here, "..", "..", "..", "crates", "tpt-bastion-ir", "src", "lib.rs");
const source = readFileSync(rust, "utf8");
const match = source.match(/pub const IR_VERSION: u32 = (\d+);/);
if (!match) {
  throw new Error(`could not find IR_VERSION in ${rust}`);
}
const out = join(here, "..", "src", "ir-version.ts");
writeFileSync(
  out,
  `// Generated by scripts/gen-ir-version.mjs from crates/tpt-bastion-ir. Do not edit.\nexport const IR_VERSION = ${match[1]};\n`
);
console.log(`wrote ${out} (IR_VERSION = ${match[1]})`);
