"""Generate bastion/_ir_version.py from the Rust source of truth.

The IR version is read from crates/tpt-bastion-ir/src/lib.rs, so the Python
binding cannot drift from the compiler. Run before building the package.
"""

import pathlib
import re

here = pathlib.Path(__file__).resolve().parent
rust = here.parents[2] / "crates" / "tpt-bastion-ir" / "src" / "lib.rs"
match = re.search(r"pub const IR_VERSION: u32 = (\d+);", rust.read_text(encoding="utf-8"))
if not match:
    raise SystemExit(f"could not find IR_VERSION in {rust}")
out = here.parent / "bastion" / "_ir_version.py"
out.write_text(
    "# Generated by scripts/gen_ir_version.py from crates/tpt-bastion-ir. Do not edit.\n"
    f"IR_VERSION = {match.group(1)}\n",
    encoding="utf-8",
)
print(f"wrote {out} (IR_VERSION = {match.group(1)})")
